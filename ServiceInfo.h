#pragma once
#include "Common.h"
#include <winsvc.h>
#include <memory>
#include <vector>

// ---------------------------------------------------------------------------
// Сервисы Windows.
//
// Модуль хранит два независимых снимка:
//   * каталог всех установленных сервисов для окна выбора;
//   * runtime-карту «pid -> активные сервисы» для правил и подписей соединений.
//
// Каталог читается только по запросу интерфейса. Runtime-карта обновляется
// фоновым потоком: в desktop всегда для таблицы, в службе — пока включено
// хотя бы одно условие «сервис». Поэтому обработчик соединения никогда не
// выполняет EnumServicesStatusExW сам.
//
// Один процесс (svchost.exe) обслуживает несколько сервисов, и ни в таблицах
// соединений ОС, ни в событиях транспорта сведений об этом нет — источником
// соответствия остаётся SCM.
// ---------------------------------------------------------------------------
struct ServiceEntry {
    std::wstring name;              // ключ сервиса (lpServiceName)
    std::wstring display;           // отображаемое имя, зависит от языка ОС
    DWORD        pid   = 0;         // 0 — сервис не выполняется
    DWORD        state = 0;         // SERVICE_*
    DWORD        type  = 0;         // SERVICE_WIN32_OWN_PROCESS / _SHARE_PROCESS
    bool         installed = true;  // false — имя взято из правила, а не из SCM

    bool running() const { return state == SERVICE_RUNNING; }
    std::wstring StateTextRu() const;
};

namespace ServiceInfo {

// Полный список установленных сервисов для окна выбора, отсортирован по имени.
// Он не участвует в периодическом runtime-опросе. refresh=true принудительно
// перечитывает каталог (кнопка «Обновить»).
std::vector<ServiceEntry> All(bool refresh = false);

// Отображаемое имя по ключу; пусто, если сервис не найден в доступном каталоге.
std::wstring DisplayName(const std::wstring& name);
bool         Installed(const std::wstring& name);

// Ссылка удерживает только неизменяемый список данного PID, а не весь runtime-
// снимок. Matcher читает его без копирования даже после публикации новой версии.
using HostedServices = std::shared_ptr<const std::vector<ServiceEntry>>;

// Активные сервисы, которые обслуживает процесс.
//
// Обычный вызов только читает опубликованный runtime-снимок и никогда не
// обращается к SCM. refresh=true предназначен для редкого UI-пути создания
// заготовки правила: он синхронно обновляет просроченный снимок.
//
// Пустой список означает, что в опубликованном снимке нет сервисов этого PID
// либо снимок ещё не готов; условие «сервис» не выполняется. Для pid=0 SCM не опрашивается.
HostedServices ServicesOfPid(DWORD pid, bool refresh = false);

// Точное сравнение ключей без учёта регистра, без обработки масок.
// Маски условий правил проверяет ServiceNameMatches.
bool SameName(const std::wstring& a, const std::wstring& b);

// Включить либо приостановить фоновое обновление runtime-карты. Поток создаётся
// лениво и остаётся спящим после disable, чтобы частые правки правил не создавали
// новые системные потоки.
void SetMonitoring(bool enabled);

// Desktop получает сообщение после смены runtime-карты либо завершения
// запрошенного опроса, даже если карта не изменилась. Служебный процесс окно
// не регистрирует. nullptr снимает уведомление.
void SetNotification(HWND window, UINT message);

// Остановить фоновый поток перед завершением процесса. Вызов идемпотентен.
void Shutdown();

// Поколение runtime-снимка. Значение меняется после первого успешного полного
// перечисления и при изменении соответствия PID -> ключевые имена сервисов.
// refresh=true выполняет принудительный синхронный опрос; обычное чтение не
// запускает RPC.
uint64_t Version(bool refresh = false);

// Запросить полный фоновый опрос перед выдачей pending в UI. Ticket подтверждает
// только успешное перечисление, начатое после запроса; уже выполняющийся опрос
// его не закрывает. Запросы до начала следующего опроса объединяются.
// SCM здесь не вызывается. При выключенном мониторе возвращается 0.
uint64_t RequestRefresh();
bool RefreshComplete(uint64_t ticket);

// Сделать runtime-снимок просроченным и разбудить монитор, если он включён.
// Последний полный снимок сохраняется до успешного обновления.
void Invalidate();

// Короткий TTL ограничивает окно устаревания. В steady state опрос выполняет
// только фоновый поток; старт и перечитывание правил службы подготавливают
// снимок синхронно до приёма локальных событий.
inline constexpr ULONGLONG kCacheTtlMs = 1000;

} // namespace ServiceInfo
