#include "Common.h"

// ---------------------------------------------------------------------------
// Принудительный разрыв ОДНОГО TCP-соединения или UDP-потока.
//
// Разрыв — не блокировка: правило не создаётся, вердикт не выносится,
// припаркованные обязательства не затрагиваются. Для TCP ядру сообщается, что
// блок управления передачей (TCB) данного соединения нужно удалить. Для UDP
// драйверу передаётся полный IPv4/IPv6 tuple, и драйвер прерывает активный
// WFP-поток по этому tuple. В обоих случаях приложение получает обычный
// сетевой результат разрыва и вправе открыть поток заново. Поэтому разрыв и
// блокировка — разные команды: первая действует один раз, вторая действует
// всегда.
//
// ---- почему это возможно далеко не для каждой строки ----------------------
//
// TCP разрывается через SetTcpEntry с состоянием MIB_TCP_STATE_DELETE_TCB.
// UDP разрывается штатной командой PortmasterKext abortUdpFlowV4/V6: она
// работает только для активного потока, который драйвер отслеживает по полному
// пятиэлементному tuple.
//
//   * протокол. Поддерживаются только TCP и UDP. Для ICMP, GRE, ESP и любых
//     других протоколов строка описывает пакеты, а не объект, который можно
//     разорвать;
//
//   * семейство адресов. SetTcpEntry принимает только TCP IPv4. UDP поддерживает
//     и IPv4, и IPv6 через две соответствующие команды драйвера;
//
//   * состояние. У прослушивающего TCP-сокета соединения ещё нет; у закрытого
//     TCP и у TIME_WAIT его уже нет. Для UDP состояние TCP не используется:
//     команда применяется к наблюдаемому активному потоку;
//
//   * адреса и порты. Для UDP драйвер отыскивает поток по полному tuple, поэтому
//     неизвестная удалённая сторона или порт делают команду недоступной;
//
//   * права. Прямое управление драйвером и удаление TCB чужого процесса требуют
//     прав администратора. В proxy-режиме UDP-команда проходит через службу,
//     которая уже владеет привилегированным дескриптором драйвера.
//
// Все случаи выясняются ДО показа меню (Check) и ровно один раз превращаются
// в неактивный пункт с указанием причины.
//
// Соединение IPv4, открытое через сокет двойного стека (адрес ::ffff:a.b.c.d),
// с точки зрения таблиц ОС является записью IPv6 и для TCP здесь тоже считается
// IPv6: его TCB принадлежит модулю IPv6, и SetTcpEntry его не находит.
// ---------------------------------------------------------------------------
namespace ConnKill {

enum class Denial : uint8_t {
    None = 0,        // разорвать можно
    NoConnection,    // выбрана строка процесса либо не выбрано ничего
    NoTcb,           // протокол не поддерживается этим действием
    Ipv6NoApi,       // TCP IPv6: в системе нет средства удалить TCB
    Listener,        // прослушивание: соединения ещё нет
    Gone,            // соединение уже закрыто (CLOSED, TIME_WAIT…)
    NoRemote,        // удалённая сторона неизвестна
    NoRights,        // требуются права администратора
};

// Копия того, что нужно ядру, и ничего больше: строка списка живёт до
// следующего такта, а команда выполняется после диалога подтверждения.
struct Target {
    bool     valid = false;      // false — строки соединения нет
    Proto    proto = Proto::Tcp;
    IpAddr   local, remote;
    uint16_t lport = 0, rport = 0;
    DWORD    state = 0;          // MIB_TCP_STATE_* только для TCP
};

Denial         Check(const Target& t);
// По значению: тексты читаются из STRINGTABLE
std::wstring DenialShort(Denial d);   // короткая причина — в подпись пункта
std::wstring DenialText(Denial d);    // пояснение — в диалог
bool           Kill(const Target& t, std::wstring& error);

} // namespace ConnKill