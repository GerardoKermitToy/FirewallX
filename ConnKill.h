#include "Common.h"

// ---------------------------------------------------------------------------
// Принудительный разрыв ОДНОГО соединения.
//
// Разрыв — не блокировка: правило не создаётся, вердикт не выносится,
// припаркованные обязательства не затрагиваются. Ядру сообщается, что блок
// управления передачей (TCB) данного соединения нужно удалить: соединение
// сбрасывается, приложение получает обычную сетевую ошибку и вправе открыть
// соединение заново. Поэтому разрыв и блокировка — разные команды: первая
// действует один раз, вторая действует всегда.
//
// ---- почему это возможно далеко не для каждой строки ----------------------
//
// Здесь используется SetTcpEntry с состоянием MIB_TCP_STATE_DELETE_TCB.
// Доступность команды определяется ограничениями API и выбранным набором
// состояний TCP:
//
//   * протокол. SetTcpEntry удаляет только TCP TCB. Для UDP, ICMP, GRE, ESP
//     и любых других протоколов этот API неприменим, независимо от того,
//     поддерживает ли сам протокол понятие соединения;
//
//   * семейство адресов. SetTcpEntry принимает MIB_TCPROW, то есть адреса
//     IPv4. Для IPv6 (MIB_TCP6ROW) парной функции в Windows НЕТ — ни
//     SetTcp6Entry, ни аналога в IP Helper. Известные обходные пути опираются
//     на недокументированный NsiSetAllParameters из nsi.dll: там задаются
//     внутренние структуры модуля TCP, состав и нумерация которых меняются
//     между сборками системы, а ошибка означает запись мусора в ядро. Такой
//     ценой возможность разрывать соединения IPv6 не покупается;
//
//   * состояние. У прослушивающего сокета соединения ещё нет; у закрытого и
//     у TIME_WAIT его уже нет: TCB либо отсутствует, либо додерживается ядром
//     до истечения 2·MSL и исчезнет сам;
//
//   * права. Удаление TCB чужого процесса требует прав администратора.
//
// Все случаи выясняются ДО показа меню (Check) и ровно один раз превращаются
// в неактивный пункт с указанием причины.
//
// Соединение IPv4, открытое через сокет двойного стека (адрес ::ffff:a.b.c.d),
// с точки зрения таблиц ОС является записью IPv6 и здесь тоже считается
// IPv6: его TCB принадлежит модулю IPv6, и SetTcpEntry его не находит.
// ---------------------------------------------------------------------------
namespace ConnKill {

enum class Denial : uint8_t {
    None = 0,        // разорвать можно
    NoConnection,    // выбрана строка процесса либо не выбрано ничего
    NoTcb,           // протокол соединения не образует
    Ipv6NoApi,       // TCP IPv6: в системе нет средства удалить TCB
    Listener,        // прослушивание: соединения ещё нет
    Gone,            // соединение уже закрыто (CLOSED, TIME_WAIT…)
    NoRemote,        // удалённая сторона неизвестна
    NoRights,        // требуются права администратора
};

// Копия того, что нужно ядру, и ничего больше: строка списка живёт до
// следующего такта, а команда выполняется после диалога подтверждения.
struct Target {
    bool     valid = false;      // false — строки соединения нет
    Proto    proto = Proto::Tcp;
    IpAddr   local, remote;
    uint16_t lport = 0, rport = 0;
    DWORD    state = 0;          // MIB_TCP_STATE_*
};

Denial         Check(const Target& t);
// По значению: тексты читаются из STRINGTABLE
std::wstring DenialShort(Denial d);   // короткая причина — в подпись пункта
std::wstring DenialText(Denial d);    // пояснение — в диалог
bool           Kill(const Target& t, std::wstring& error);

} // namespace ConnKill